"""Generate the data files the static site loads:

  site/data/content.js    window.TARTEEL = {...}   (a <script>, so the site also
                                                    works when opened from disk)
  site/css/tajweed.css    one CSS variable + class per tajweed rule color

Everything else in site/ (HTML, CSS, JS, fonts, audio) is hand-written or
produced by build_audio.py.
"""
from __future__ import annotations

import json

import quran_data as q

ROOT = q.ROOT
SITE = ROOT / "site"


def tajweed_css(legend: list[dict]) -> str:
    light = "\n".join(f"  --tj-{c['id']}: {c['light']};" for c in legend)
    dark = "\n".join(f"    --tj-{c['id']}: {c['dark']};" for c in legend)
    dark2 = "\n".join(f"  --tj-{c['id']}: {c['dark']};" for c in legend)
    classes = "\n".join(f".tj-{c['id']} {{ color: var(--tj-{c['id']}); }}" for c in legend)
    bgs = "\n".join(f".bg-{c['id']} {{ background: var(--tj-{c['id']}); }}" for c in legend)
    return f"""/* GENERATED by tools/build_site.py from content/legend.json. Do not edit. */
:root {{
{light}
}}
@media (prefers-color-scheme: dark) {{
  :root:not([data-theme="light"]) {{
{dark}
  }}
}}
:root[data-theme="dark"] {{
{dark2}
}}
{classes}
{bgs}
"""


def main() -> None:
    model = json.loads((ROOT / "build" / "model.json").read_text("utf8"))
    (SITE / "data").mkdir(parents=True, exist_ok=True)
    (SITE / "css").mkdir(parents=True, exist_ok=True)
    payload = json.dumps(model, ensure_ascii=False, separators=(",", ":"))
    (SITE / "data" / "content.js").write_text(f"window.TARTEEL={payload};\n", "utf8")
    (SITE / "css" / "tajweed.css").write_text(tajweed_css(model["legend"]), "utf8")
    kb = (SITE / "data" / "content.js").stat().st_size / 1024
    print(f"site/data/content.js {kb:.0f} KB, site/css/tajweed.css written")


if __name__ == "__main__":
    main()
